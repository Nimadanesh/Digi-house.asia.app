def load(path):
    with io.open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def dump(path, data):
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")


def main():
    for locale in LOCALES:
        path = f"messages/{locale}.json"
        data = load(path)
        prop = data.setdefault("property", {})
        for key in REMOVE_PROPERTY:
            prop.pop(key, None)
        for key, values in KEYS.items():
            prop[key] = values[locale]
        common = data.setdefault("common", {})
        for key, values in COMMON_KEYS.items():
            common[key] = values[locale]
        dump(path, data)
        print(f"updated {path}")


